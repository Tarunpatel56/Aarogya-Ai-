export async function ensureVerifiedHospitalsSeeded(): Promise<void> {
  try {
    for (const h of VERIFIED_HOSPITALS_SEED) {
      await prisma.hospital.upsert({
        where: { licenseNumber: h.licenseNumber },
        create: h,
        update: {
          name: h.name,
          address: h.address,
          city: h.city,
          state: h.state,
          latitude: h.latitude,
          longitude: h.longitude,
          contactPhone: h.contactPhone,
          emergencyPhone: h.emergencyPhone,
          availableIcuBeds: h.availableIcuBeds,
          totalIcuBeds: h.totalIcuBeds,
          availableNormalBeds: h.availableNormalBeds,
          totalNormalBeds: h.totalNormalBeds,
          hasEmergencyBay: h.hasEmergencyBay,
          hasTraumaCenter: h.hasTraumaCenter,
        },
      });
    }
    logger.info(`Successfully synchronized ${VERIFIED_HOSPITALS_SEED.length} verified hospitals across India.`);
  } catch (err: any) {
    logger.warn('Hospital seed skipped or already satisfied:', { error: err.message });
  }
}

